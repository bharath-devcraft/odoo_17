    @api.onchange('service_id', 'service_ids')
    def onchange_service_ids(self):
        codes = []
        if self.service_id:
            codes.append(self.service_id.sys_ref)
            self.bus_location = self.service_id.bus_location
            if self.service_id.sys_ref in ('ISTL', 'DOTL'):
                self.container_category = 'empty'
            else:
                 self.container_category = 'laden'
                 self.empty_or_laden = 'empty'
            if self.service_id.sys_ref == 'DOTL':
                tank_rec = self.env['cm.tank.operator'].search(
                    [('short_name', '=', 'GMPL'), ('status', '=', 'active'), 
                    ('active_trans', '=', True)], limit=1
                )
            self.rep_is_required = 'no'
            self.payment_term_id = self.service_id.payment_term_id.id
            self.line_ids_k = False
            self.line_ids_k = self.create_teams_and_conditions_line(self.service_id.id)				
        if self.service_ids:
            codes.extend(self.service_ids.mapped('sys_ref'))
            for service_id in self.service_ids:
                self.line_ids_k = False
                self.line_ids_k = self.create_teams_and_conditions_line(service_id.id)
        self.combined_codes = list(set(codes))

    def create_teams_and_conditions_line(self, service_id):
        teams_and_conditions_line = []
        for service_line in self.env["cm.terms.conditions"].search([('service_id', '=', service_id)], limit=1).line_ids:
            teams_and_conditions_line.append((0, 0, {
            'description': service_line.term_cond}))
        return teams_and_conditions_line
            
