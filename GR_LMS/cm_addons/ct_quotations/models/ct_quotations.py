    def dott_pricing_cost(self, vals):
        dott_pricing_cost_lines = []
        required_keys = ['rail_pol_port_id', 'rail_pod_port_id', 'header_id', 'container_category', 'dg_product', 'tank_capacity',\
            'ship_term_id', 'bus_location', 'trip_days', 'drop_depot_id', 'tank_tcode_id', 'product_id', 'coastal_pol_port_id','coastal_pod_port_id']
        if all(key in vals for key in required_keys):
            if self.is_parent:
                child_records = self.env['ct.quotations'].search([('enquiry_no', '=', self.enquiry_no), ('is_parent', '=', False)])
                pol_free_days = 0
                pod_free_days = 0
                transit_days = 0
                for child_record in child_records:
                    pol_free_days += child_record.dotr_pol_free_days
                    pod_free_days += child_record.dotr_pod_free_days 
                    transit_days += child_record.tot_transit_days            

                rail_tariff_domain = [('pol_port_id','=', self.rail_pol_port_id.id), ('pod_port_id', '=', self.rail_pod_port_id.id),\
                        ('container_category', '=', self.container_category), ('status', '=', 'active'),('active_trans', '=', True)]                   
                rail_tariff_id = self.env['cm.rail.tariff'].search(rail_tariff_domain, order='eff_from_date desc', limit=1) 
                if "DOTT" in self.combined_codes:
                    self.estimated_days = self.rail_pol_free_days + self.rail_pod_free_days + rail_tariff_id.transit_days + pol_free_days + pod_free_days + transit_days
                if "DOTC" in self.combined_codes:
                    self.estimated_days = self.coastal_pol_free_days + self.coastal_pod_free_days + pol_free_days + pod_free_days + transit_days                    
            if 'DOTT' in vals['combined_codes']:
                dott_pricing_cost_lines = dott_pricing_cost_lines + self._rail_tariff(vals)
            dotl_vals = vals.copy()
            dotl_vals['service_id'] = self.env[CM_SERVICE].search([('sys_ref', '=', 'DOTL'),('status', '=', 'active'),\
                ('active_trans', '=', True)], limit=1).id
            for istl_line in self.istl_pricing_cost(dotl_vals):
                dott_pricing_cost_lines.append(istl_line)                             
            port_vals = vals.copy()
            port_vals['pol_port_id'] = vals['rail_pol_port_id']
            port_vals['pod_port_id'] = vals['rail_pod_port_id']
            if 'DOTC' in vals['combined_codes']:
                port_vals['pol_port_id'] = vals['coastal_pol_port_id']
                port_vals['pod_port_id'] = vals['coastal_pod_port_id']  
            if self.coastal_pol_terminal_id and self.coastal_pod_terminal_id:
                 port_vals['pol_terminal_id'] = self.coastal_pol_terminal_id.id
                 port_vals['pod_terminal_id'] = self.coastal_pod_terminal_id.id         
            if self.is_parent:
                additional_servicer_record = self._additional_service_data(vals)
                self.line_ids_c.create(additional_servicer_record)                  
            for pol_port_tariff_line in self._pol_port_tariff(port_vals):
                dott_pricing_cost_lines.append(pol_port_tariff_line)
            for pod_port_tariff_line in self._pod_port_tariff(port_vals):
                dott_pricing_cost_lines.append(pod_port_tariff_line)
            for door_tariff_line in self._door_tariff(port_vals):
                dott_pricing_cost_lines.append(door_tariff_line)                                                 
