    def _create_quotations_details_line(self):
        
        if len(list(set([line.grouping for line in self.line_ids_c]))) <= 1:
            default_qty = 1
            unit_price = 0
            if 'ISTL' in self.combined_codes and self.price_owner == 'agent':
                unit_price = sum([line.tot_value for line in self.line_ids_d]) + self.agent_markup_value
            elif 'ISTL' in self.combined_codes: 
                unit_price = self.customer_value                
            elif 'DOTL' in self.combined_codes:
                unit_price = sum([line.tot_amt for line in self.line_ids_c]) + self.agent_markup_value
            elif 'OSTE' in self.combined_codes and self.price_owner == 'agent':
                unit_price = self.total_expense + self.oste_markup_value + self.agent_markup_value  
            elif any(code in self.combined_codes for code in ('OSTI', 'OSTE', 'OSNR', 'OSNB')) and self.price_owner != 'agent':
                unit_price = self.selling_value              
            elif 'OSTI' in self.combined_codes and self.price_owner == 'agent':
                unit_price =  sum(self.line_ids_c.mapped('tot_amt')) + self.agent_markup_value              
            elif 'OSNR' in self.combined_codes:
                unit_price = self.total_expense + self.oste_markup_value + self.agent_markup_value 
            elif 'OSNB' in self.combined_codes:
                unit_price = self.total_expense + self.oste_markup_value + self.agent_markup_value                          
            else:
                unit_price = sum(self.line_ids_c.mapped('tot_amt'))
                
            self.line_ids_g.create({
                "header_id": self.id,
                "chrg_head_id": self.service_id.pri_chrg_head_id.id,
                "description": self.service_id.pri_chrg_head_id.name,
                "uom_id": self.env['uom.uom'].search([('short_name', '=', 'UN'),('status', '=', 'active'),('active_trans', '=', True)], limit=1).id,
                "qty": default_qty,
                "unit_price":unit_price,
                "tot_amt":  unit_price,
                "currency_id": self.quotation_currency_id.id,
            })  
                
        else:            
            for grp in [ f'g{no}' for no in range(1, 11)]:
                customer_price = self.env['ct.quotations.pricing.details.line']
                check_uom_records = customer_price.search([('header_id', '=', self.id), ('grouping', '=', grp)])
                group_count = customer_price.search_count([('header_id', '=', self.id), ('grouping', '=', grp)])
                if group_count > 1 and len(list(set([uom.uom_id.id for uom in check_uom_records]))) > 1:
                    raise UserError("Grouping is not allowed if charge head UOM is different.")
                                    
            custom_price_lines = []
            for line in self.line_ids_c:
                custom_price_lines.append({
                'group': line.grouping,
                'chrg_head_id': line.chrg_head_id.id,
                'uom_id': line.uom_id.id,
                'qty': line.qty,
                'unit_price': line.tot_amt,
                'currency_id': line.quotation_currency_id.id,
                }) 
                
            result = defaultdict(lambda: {'unit_price': 0})
            
            charge_head = defaultdict(lambda: {'chrg_head_id': []})
            
            
            for item in custom_price_lines:
                group = item['group']
                charge_head[group]['chrg_head_id'] += [item['chrg_head_id']]
                result[group]['chrg_head_id'] = item['chrg_head_id'] if len(charge_head[group]['chrg_head_id'] if charge_head else []) <=1 else False
                result[group]['description'] = self.env['cm.charges.heads'].search([('id', '=', item['chrg_head_id'])], limit=1).name if len(charge_head[group]['chrg_head_id'] if charge_head else []) <=1 else False                                
                result[group]['uom_id'] = item['uom_id']
                result[group]['currency_id'] = item['currency_id']                       
                result[group]['qty'] = 1
                result[group]['unit_price'] += item['unit_price']
                
                
            grouped_data = {k: v for k, v in result.items()}   
            self.line_ids_g = [(0, 0, grouped_data[grp]) for grp in grouped_data]
            
            if self.oste_markup_value != 0:
                if self.service_id.pri_chrg_head_id.id and not [line for line in self.line_ids_g if self.service_id.pri_chrg_head_id.id == line.chrg_head_id.id]:
                    raise UserError(f"{self.service_id.pri_chrg_head_id.name} charge head grouping is not allowed. Because markup value to be added in that charge head only.")
                else:
                    primary_charge_head = self.env['ct.quotations.child.line'].search([('header_id', '=', self.id), ('chrg_head_id', '=', self.service_id.pri_chrg_head_id.id)], limit=1)
                    if self.oste_markup_value:
                        primary_charge_head.unit_price += self.oste_markup_value
       
        
