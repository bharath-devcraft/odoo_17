    def find_port_route_sequence(self, service_route, pol, pod):
        if service_route and pol and pod:
            start_port_seq = 0
            end_port_seq = 0
            vessel_service_route = self.env[CM_VESSEL_SERVICE_ROUTE].search([('id', '=', service_route),('status', '=', 'active'),\
                ('active_trans', '=', True)])
            for service_route_line in vessel_service_route.line_ids:
                if pol == service_route_line.port_id.id:
                    start_port_seq = service_route_line.entry_seq
                if pod == service_route_line.port_id.id:
                    end_port_seq = service_route_line.entry_seq
            skip_pol_port_count = 1
            return [line.port_id.id for line in vessel_service_route.line_ids if line.entry_seq in [seq for seq in range(start_port_seq, end_port_seq + skip_pol_port_count)]]  
       
                  
                
