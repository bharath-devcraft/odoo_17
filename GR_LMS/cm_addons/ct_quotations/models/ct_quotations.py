    def  get_default_mail_ids(self, **kw):
        mail_ids = {}
        trans_rec = self.env[CT_QUOTATIONS].search([('id', '=', kw.get('trans_id', False))])
        if kw.get('entry_action', self) == 'entry_approve':
            if trans_rec and trans_rec.user_id.email:
                mail_ids['email_to'] = [trans_rec.user_id.email]
        if kw.get('entry_action', self) == 'entry_revise':   
            if trans_rec and trans_rec.user_id.email:
                mail_ids['email_to'] = list(set([trans_rec.user_id.email, trans_rec.confirm_user_id.email, trans_rec.ap_rej_user_id.email, trans_rec.revised_user_id.email]))
        
        if kw.get('entry_action', self) in ('entry_reject','entry_cancel'):  
            if trans_rec and trans_rec.cancel_user_id.email:
                mail_ids['email_cc'] = list(set([trans_rec.cancel_user_id.email]))
            
            email_to=[]
            if trans_rec and trans_rec.executed_user_id.email:
                email_to.append(trans_rec.executed_user_id.email)
            if trans_rec and trans_rec.generated_user_id.email:
                email_to.append(trans_rec.generated_user_id.email)
            if trans_rec and trans_rec.confirm_user_id.email:
                email_to.append(trans_rec.confirm_user_id.email)

            if email_to:
                mail_ids['email_to'] = list(set(email_to))

        return mail_ids
    
